export const staffDepartments=[...new Set(staffListings.map(person=>person.department))];
const normalize=value=>String(value).normalize('NFKD').replace(/[\u0300-\u036f]/g,'').toLowerCase().replace(/[^a-z0-9]+/g,' ').trim();
/** Exact published department plus tokenized name/role search; never infers a student assignment.
 * @param {typeof staffDirectory} staff
 * @param {string} query
 * @param {string} department
 */
export function filterStaff(staff,query='',department='all') {
 const terms=normalize(query).split(/\s+/).filter(Boolean);
 return staff.filter(person=>(department==='all'||person.departments.includes(department))&&terms.every(term=>normalize(`${person.name} ${person.roles.map(item=>`${item.role} ${item.department}`).join(' ')}`).includes(term)));
}
