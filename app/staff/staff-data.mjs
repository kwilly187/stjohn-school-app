// Combine only identical published name AND email; never resolve a spelling conflict by guesswork.
const contacts=new Map();
for(const listing of staffListings) {
 const key=JSON.stringify([listing.name,listing.email]);
 const existing=contacts.get(key);
 const assignment={role:listing.role,department:listing.department};
 if(existing) {
  if(!existing.roles.some(item=>item.role===assignment.role&&item.department===assignment.department))existing.roles.push(assignment);
  if(!existing.departments.includes(listing.department))existing.departments.push(listing.department);
  existing.contactNeedsConfirmation ||= listing.contactNeedsConfirmation;
 } else contacts.set(key,{id:listing.id,name:listing.name,email:listing.email,roles:[assignment],departments:[listing.department],contactNeedsConfirmation:listing.contactNeedsConfirmation});
}
/** @type {Array<{id:string,name:string,email:string|null,roles:Array<{role:string,department:string}>,departments:string[],contactNeedsConfirmation:boolean}>} */
